// Writes supabase/seed/fbla_questions.sql: the question catalogue the database grades against
// (id, event, sub, diff, q, choices, answer, explain). Re-run and apply after changing any content/*.json.
//   node scripts/catalogue-sql.mjs            -> one file, one upsert per event (about 650 KB)
//   node scripts/catalogue-sql.mjs --check    -> also prints the checksum the database should match:
//     select md5(string_agg(id || ':' || answer || ':' || md5(q || choices::text || coalesce(explain, '')), ',' order by id collate "C"))
//     from public.fbla_questions;
// The seed is too big to paste through the Supabase MCP in one go. Once content is pushed to GitHub main, the
// database can load it itself with pg_net (0008): net.http_get the raw content/<slug>.json files, then upsert
// from net._http_response with the same jsonb_to_recordset shape used below, and compare the checksum.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lit = s => `'${String(s).replace(/'/g, "''")}'`;
const md5 = s => createHash('md5').update(s, 'utf8').digest('hex');

const events = [];
for (const f of readdirSync(join(root, 'content')).filter(f => f.endsWith('.json')).sort()) {
  const d = JSON.parse(readFileSync(join(root, 'content', f), 'utf8'));
  const prefix = d.questions[0].id.split('-')[0];
  d.questions.forEach((x, i) => {
    if (x.id !== `${prefix}-${String(i + 1).padStart(3, '0')}`) throw new Error(`${f}: ids must run ${prefix}-001 up`);
    if (!Array.isArray(x.choices) || x.choices.length !== 4) throw new Error(`${x.id}: needs 4 choices`);
    if (!(x.answer >= 0 && x.answer <= 3)) throw new Error(`${x.id}: answer must be 0-3`);
    if (![1, 2, 3].includes(x.diff)) throw new Error(`${x.id}: diff must be 1-3`);
    if (!d.subs.includes(x.sub)) throw new Error(`${x.id}: unknown area ${x.sub}`);
  });
  events.push(d);
}

const rows = events.flatMap(d => d.questions.map(x => ({ ...x, event: d.slug })));
const header =
  '-- Generated by scripts/catalogue-sql.mjs from content/*.json. Do not edit by hand.\n' +
  `-- ${rows.length} questions in ${events.length} events.\n`;
const parts = events.map(d => {
  // jsonb array of the event's questions, unpacked server-side: one literal per event keeps the file simple
  const payload = JSON.stringify(d.questions.map(x => ({
    id: x.id, sub: x.sub, diff: x.diff, q: x.q, choices: x.choices, answer: x.answer, explain: x.explain ?? null,
  })));
  return (
    `insert into public.fbla_questions (id, event, sub, diff, q, choices, answer, explain)\n` +
    `select x.id, ${lit(d.slug)}, x.sub, x.diff, x.q, x.choices, x.answer, x.explain\n` +
    `from jsonb_to_recordset(${lit(payload)}::jsonb)\n` +
    `  as x(id text, sub text, diff smallint, q text, choices jsonb, answer smallint, explain text)\n` +
    `on conflict (id) do update set event = excluded.event, sub = excluded.sub, diff = excluded.diff,\n` +
    `  q = excluded.q, choices = excluded.choices, answer = excluded.answer, explain = excluded.explain;\n`
  );
});
const sql = header + parts.join('\n') +
  `\n-- drop questions that no longer exist in content (answers keep their history)\n` +
  `delete from public.fbla_questions where id not in (${rows.map(r => lit(r.id)).join(',')});\n`;

mkdirSync(join(root, 'supabase', 'seed'), { recursive: true });
writeFileSync(join(root, 'supabase', 'seed', 'fbla_questions.sql'), sql);
console.log(`catalogue: ${rows.length} questions, ${sql.length} bytes -> supabase/seed/fbla_questions.sql`);

if (process.argv.includes('--check')) {
  // Postgres jsonb::text prints arrays as ["a", "b"] (comma + space) with JSON string escaping
  const jsonbText = arr => '[' + arr.map(s => JSON.stringify(s)).join(', ') + ']';
  const sorted = [...rows].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const agg = sorted.map(r => `${r.id}:${r.answer}:${md5(r.q + jsonbText(r.choices) + (r.explain ?? ''))}`).join(',');
  console.log(`checksum: ${md5(agg)}`);
}
